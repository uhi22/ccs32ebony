#!/usr/bin/env python3
"""Pack the web UI (web/index.html) into webui_assets.h as a gzip-compressed byte array.

Usage:
    python tools/pack_web.py

Run it after every change in web/. The generated header is committed, so the sketch builds
without Python. The output is reproducible (fixed gzip timestamp), so an unchanged page gives an
unchanged header.
"""
import gzip
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "web" / "index.html"
TARGET = ROOT / "webui_assets.h"


def main():
    raw = SOURCE.read_bytes()
    packed = gzip.compress(raw, compresslevel=9, mtime=0)
    lines = []
    for i in range(0, len(packed), 16):
        lines.append("  " + ", ".join("0x%02x" % b for b in packed[i:i + 16]) + ",")
    header = (
        "// Generated by tools/pack_web.py from web/index.html - do not edit.\n"
        "// %d bytes raw, %d bytes gzip.\n\n"
        "#pragma once\n\n"
        "#include <Arduino.h>\n\n"
        "static const uint8_t INDEX_HTML_GZ[] PROGMEM = {\n%s\n};\n"
        "static const size_t INDEX_HTML_GZ_LEN = sizeof(INDEX_HTML_GZ);\n"
    ) % (len(raw), len(packed), "\n".join(lines))
    TARGET.write_text(header, encoding="ascii", newline="\n")
    print("%s: %d bytes raw -> %d bytes gzip" % (TARGET.name, len(raw), len(packed)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
